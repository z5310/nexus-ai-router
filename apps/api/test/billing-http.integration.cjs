require('ts-node').register({ files: true, project: require('node:path').join(__dirname, '../tsconfig.json') })
require('reflect-metadata')
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { config } = require('dotenv')
config({ path: require('node:path').join(__dirname, '../../../.env'), quiet: true })
const { NestFactory } = require('@nestjs/core')
const { ValidationPipe } = require('@nestjs/common')
const { FastifyAdapter } = require('@nestjs/platform-fastify')
const { DataSource } = require('typeorm')
const { AppModule } = require('../src/app.module')
const { AuthService } = require('../src/identity/auth.service')
const { ConfigService } = require('@nestjs/config')

async function main() {
  const app = await NestFactory.create(AppModule, new FastifyAdapter(), { logger: false })
  const users = []
  try {
    app.useGlobalPipes(new ValidationPipe({ whitelist: true, transform: true, errorHttpStatusCode: 422 }))
    await app.init()
    const server = app.getHttpAdapter().getInstance()
    await server.ready()
    const auth = app.get(AuthService)
    const db = app.get(DataSource)
    for (let index = 0; index < 2; index++) {
      const issued = await auth.register({ name: 'Billing HTTP test', email: `billing-http-${randomUUID()}@example.invalid`, password: `Test-only-${randomUUID()}!` }, {})
      users.push(issued)
    }
    const [otherWorkspace] = await db.query('SELECT id FROM workspaces WHERE created_by_user_id = $1', [users[1].user.id])
    const headers = { authorization: `Bearer ${users[0].accessToken}` }
    assert.equal((await server.inject({ method: 'GET', url: '/api/admin/billing/workspaces', headers })).statusCode, 403)
    await db.query("UPDATE users SET role = 'admin' WHERE id = $1", [users[0].user.id])
    assert.equal((await server.inject({ method: 'GET', url: '/api/admin/billing/workspaces', headers })).statusCode, 200)
    assert.equal((await server.inject({ method: 'GET', url: '/api/admin/billing/not-a-uuid', headers })).statusCode, 400)
    assert.equal((await server.inject({ method: 'GET', url: '/api/admin/billing/workspaces?page=-1', headers })).statusCode, 422)
    assert.equal((await server.inject({ method: 'POST', url: `/api/admin/billing/${otherWorkspace.id}/grants`, headers, payload: { operationId: randomUUID(), amount: '-1', reason: 'validation only', evidence: 'test-case' } })).statusCode, 422)
    assert.equal((await server.inject({ method: 'POST', url: `/api/admin/billing/${otherWorkspace.id}/grants`, headers: { authorization: `Bearer ${users[1].accessToken}` }, payload: { operationId: randomUUID(), amount: '1', reason: 'permission test', evidence: 'test-case' } })).statusCode, 403)
    assert.equal((await server.inject({ method: 'GET', url: '/api/billing/balance' })).statusCode, 401)
    const balance = await server.inject({ method: 'GET', url: '/api/billing/balance', headers })
    assert.equal(balance.statusCode, 200)
    assert.deepEqual(balance.json(), { currency: 'CNY', available: '0.000000', reserved: '0.000000' })
    assert.deepEqual((await server.inject({ method: 'GET', url: '/api/billing/status', headers })).json(), { chatEnabled: false, currency: 'CNY' })
    assert.deepEqual((await server.inject({ method: 'GET', url: '/api/billing/pending', headers })).json(), { data: [] })
    assert.equal((await server.inject({ method: 'GET', url: '/api/billing/pending', headers: { ...headers, 'x-workspace-id': otherWorkspace.id } })).statusCode, 403)
    assert.equal((await server.inject({ method: 'GET', url: '/api/billing/balance', headers: { ...headers, 'x-workspace-id': otherWorkspace.id } })).statusCode, 403)
    assert.deepEqual((await server.inject({ method: 'GET', url: '/api/billing/ledger', headers })).json(), { data: [], nextCursor: null })
    assert.equal((await server.inject({ method: 'GET', url: '/api/billing/ledger?cursor=invalid', headers })).statusCode, 400)
    assert.equal((await server.inject({ method: 'POST', url: '/api/billing/grant', headers, payload: { amount: '100' } })).statusCode, 404)
    const [currentWorkspace] = await db.query('SELECT id FROM workspaces WHERE created_by_user_id = $1', [users[0].user.id])
    const [model] = await db.query("SELECT id, public_id FROM models WHERE is_enabled = true AND model_type = 'text' AND input_price > 0 LIMIT 1")
    assert.ok(model)
    await db.query(`INSERT INTO workspace_models (user_id, workspace_id, model_id, alias, priority, rate_limit_rpm, daily_budget_cny, enabled)
      VALUES ($1,$2,$3,'Billing test',50,60,100,true)`, [users[0].user.id, currentWorkspace.id, model.id])
    app.get(ConfigService).set('BILLING_PREPAID_WORKSPACE_IDS', currentWorkspace.id)
    assert.equal((await server.inject({ method: 'GET', url: '/api/billing/status', headers })).json().chatEnabled, true)
    const unpaid = await server.inject({ method: 'POST', url: '/api/console/playground/chat', headers, payload: { model: model.public_id, prompt: 'test' } })
    assert.equal(unpaid.statusCode, 402)
    assert.equal((await server.inject({ method: 'GET', url: '/api/billing/balance', headers })).json().reserved, '0.000000')
    console.log('PASS: billing HTTP auth, workspace isolation, decimal balance, ledger empty state, invalid cursor and no public funding endpoint')
  } finally {
    const db = app.get(DataSource)
    for (const user of users) {
      await db.query('DELETE FROM workspaces WHERE created_by_user_id = $1', [user.user.id])
      await db.query('DELETE FROM users WHERE id = $1', [user.user.id])
    }
    await app.close()
  }
}
main().catch((error) => { console.error(error); process.exitCode = 1 })
